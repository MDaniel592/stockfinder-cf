import { useEffect, useState } from 'react';
import type { Product } from '../../../packages/api-contracts/index';

const PLACEHOLDERS = new Set(['cpu', 'gpu', 'motherboard', 'ram', 'storage', 'psu', 'cooler']);
const PLACEHOLDER_WIDTHS = [160, 400, 640];
/** Category render (4:3, transparent) used when a product has no photo, or its photo fails. AVIF with WebP fallback. */
const placeholderSet = (key: string, ext: 'avif' | 'webp') => PLACEHOLDER_WIDTHS.map(w => `/images/placeholders/${key}-${w}.${ext} ${w}w`).join(', ');
export const placeholderSrc = (category: string) => `/images/placeholders/${PLACEHOLDERS.has(category) ? category : 'pc-hero'}-400.webp`;

/** 160 px WebP thumbnail generated by scripts/make_thumbnails.py next to the product photos (may not exist yet). */
const thumbFor = (path: string) => /^\/images\/products\/.+\.(png|jpe?g|webp)$/i.test(path) ? path.replace(/^\/images\/products\//, '/images/thumbs/').replace(/\.\w+$/, '.webp') : null;

/** Product photo, or the category placeholder render. `sizes` is the rendered CSS width so the browser picks the
 *  smallest adequate file (thumbnail for list rows, full photo for the product page). Fallback chain without retry
 *  loops: thumbnail+photo srcset → photo only → placeholder. */
export function ProductImage({ product, category, className = '', eager = false, sizes = '48px' }: {
  product?: Product; category: string; className?: string; eager?: boolean; sizes?: string;
}) {
  const original = product?.image_path;
  const [stage, setStage] = useState(0); // 0: srcset with thumbnail, 1: original only, 2: placeholder
  useEffect(() => setStage(0), [original]);
  const common = { className, alt: '', loading: eager ? 'eager' as const : 'lazy' as const, decoding: 'async' as const,
    ...(eager ? { fetchPriority: 'high' as const } : {}), width: 400, height: 300 };
  if (original && stage < 2) {
    const thumb = stage === 0 ? thumbFor(original) : null;
    return <img {...common} src={original} srcSet={thumb ? `${thumb} 160w, ${original} 800w` : undefined} sizes={thumb ? sizes : undefined}
      data-image-origin={product?.image_scope ?? 'model'} onError={() => setStage(s => (thumb && s === 0 ? 1 : 2))}/>;
  }
  const key = PLACEHOLDERS.has(category) ? category : 'pc-hero';
  return <picture className="ph-picture">
    <source type="image/avif" srcSet={placeholderSet(key, 'avif')} sizes={sizes}/>
    <img {...common} src={placeholderSrc(category)} srcSet={placeholderSet(key, 'webp')} sizes={sizes} data-image-origin="placeholder"/>
  </picture>;
}
