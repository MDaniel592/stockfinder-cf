const {chromium}=require('@playwright/test');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({args:['--no-sandbox']});const page=await browser.newPage({viewport:{width:1440,height:1000}});
 page.setDefaultTimeout(20000);const errors=[],forbidden=[];page.on('pageerror',e=>errors.push(e.message));
 const base=process.env.TEST_BASE_URL||'http://127.0.0.1:8800';
 await page.addInitScript(()=>localStorage.setItem('stockfinder.watchlist.v1',JSON.stringify([{slug:'amd-ryzen-7-9800x3d',name:'CPU',baseline:null,target:null,backInStock:true,initialStock:false}])));
 await page.route('**/api/v1/**',async route=>{
  const p=new URL(route.request().url()).pathname;
  if(p.startsWith('/api/v1/builder/')||p.startsWith('/api/v1/builds')||p==='/api/v1/catalog/deals') return route.continue();
  forbidden.push(p);return route.abort();
 });
 await page.goto(`${base}/ofertas`,{waitUntil:'networkidle'});
 await page.getByRole('heading',{name:'Las 20 mayores bajadas',exact:true}).waitFor();
 const cards=page.locator('.deals-page .drop-card');await cards.first().waitFor();
 assert((await cards.count())<=20);assert.equal(await page.locator('.deals-page [role=alert]').count(),0);
 await page.getByLabel('Tipo de componente').selectOption('cpu');
 await page.waitForResponse(r=>r.url().includes('catalog/deals?category=cpu'));
 await page.waitForTimeout(200);
 assert((await cards.count())<=10);
 await page.getByLabel('Tipo de componente').selectOption('');
 await cards.first().waitFor();
 await page.screenshot({path:'artifacts/stockfinder-deals.png'});
 await page.setViewportSize({width:390,height:844});assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.screenshot({path:'artifacts/stockfinder-deals-mobile.png'});
 await page.goto(`${base}/configurador`,{waitUntil:'networkidle'});
 const compareButton=page.getByRole('button',{name:'Comparar compra por tiendas',exact:true});
 assert(await compareButton.isDisabled());
 assert.equal(await compareButton.getAttribute('aria-busy'),'false');
 assert.equal(await compareButton.evaluate(b=>getComputedStyle(b).cursor),'not-allowed');
 await page.locator('#builder-slot-cpu').click();await page.locator('.part-picker.is-open [role=option]').first().click();
 await page.getByRole('button',{name:'Consultar precios actuales',exact:true}).click();
 await page.getByText(/Precios consultados en el catálogo/).waitFor();
 await page.getByRole('button',{name:'Comparar compra por tiendas',exact:true}).click();await page.locator('.purchase-plans article').first().waitFor();
 assert.deepEqual(forbidden,[],'features pages must not call any D1-backed API, including bootstrap and favorites');
 assert.deepEqual(errors,[]);
 await page.unroute('**/api/v1/**');await page.goto(base,{waitUntil:'networkidle'});
 await page.getByRole('link',{name:'Mostrar más ofertas'}).click();await page.waitForURL('**/ofertas');
 const result=await (await page.request.get(`${base}/api/v1/catalog/deals`)).json();const drops=result.data.drops;
 assert(drops.length<=20);assert.equal(new Set(drops.map(d=>d.id)).size,drops.length);
 for(let i=1;i<drops.length;i++)assert((drops[i-1].previous_price_cents-drops[i-1].min_price_cents)/drops[i-1].previous_price_cents >= (drops[i].previous_price_cents-drops[i].min_price_cents)/drops[i].previous_price_cents);
 await browser.close();console.log(`Features QA passed: ${drops.length} unique ordered deals, landing link, mobile, replica picker/prices/purchase plan, no D1-backed API requests.`);
})().catch(e=>{console.error(e);process.exit(1)});
