const {chromium}=require('@playwright/test');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({args:['--no-sandbox']});const page=await browser.newPage({viewport:{width:1440,height:1000}});page.setDefaultTimeout(15000);
 const base=process.env.TEST_BASE_URL||'http://127.0.0.1:8800';
 await page.addInitScript(()=>localStorage.setItem('stockfinder.watchlist.v1',JSON.stringify([{slug:'amd-ryzen-7-9800x3d',name:'CPU',baseline:null,target:null,backInStock:true,initialStock:false}])));
 await page.goto(`${base}/ofertas`,{waitUntil:'networkidle'});
 const button=page.getByRole('button',{name:/Favoritos y avisos/});
 assert.equal(await page.locator('.page-content .watchlist').count(),0);
 await page.locator('.watchlist-header.has-updates').waitFor();await button.click();
 const popup=page.getByRole('dialog',{name:'Favoritos y avisos',exact:true});await popup.waitFor();
 assert.match(await popup.innerText(),/Hay novedades/);await page.screenshot({path:'artifacts/stockfinder-header-favorites.png'});
 await page.keyboard.press('Escape');assert.equal(await popup.count(),0);assert(await button.evaluate(b=>b===document.activeElement));
 await button.click();await page.mouse.click(12,320);assert.equal(await popup.count(),0);
 await page.setViewportSize({width:390,height:844});await button.click();await popup.waitFor();
 const box=await popup.boundingBox();assert(box.x>=0&&box.x+box.width<=390);
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.screenshot({path:'artifacts/stockfinder-header-favorites-mobile.png'});
 await page.getByRole('button',{name:'Cerrar favoritos',exact:true}).click();
 await page.getByRole('button',{name:'Ajustes de apariencia',exact:true}).click();
 await page.getByRole('switch',{name:/Mostrar favoritos en cabecera/}).uncheck();
 await page.getByRole('button',{name:'Listo',exact:true}).click();assert.equal(await button.count(),0);
 let calls=0;page.on('request',r=>{if(r.url().includes('/watchlist?'))calls++;});
 await page.reload({waitUntil:'networkidle'});assert.equal(await button.count(),0);assert.equal(calls,0);
 assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('stockfinder.watchlist.v1')).length),1);
 await page.getByRole('button',{name:'Ajustes de apariencia',exact:true}).click();
 await page.getByRole('switch',{name:/Mostrar favoritos en cabecera/}).check();await page.getByRole('button',{name:'Listo',exact:true}).click();
 await button.waitFor();await browser.close();console.log('Header favorites QA passed: popup, contrast badge, Escape/outside close, mobile bounds, persisted hide/show and no hidden checks.');
})().catch(e=>{console.error(e);process.exit(1)});
