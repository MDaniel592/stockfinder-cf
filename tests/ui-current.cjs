// Appearance: light theme by default, theme/density persistence, "Sistema" option, product page offers, mobile.
// Usage: TEST_BASE_URL=http://127.0.0.1:8795 CHROMIUM_PATH=... node tests/ui-current.cjs
const { chromium } = require('@playwright/test');
const assert = require('node:assert/strict');
(async () => {
  const base = process.env.TEST_BASE_URL || 'http://127.0.0.1:8787';
  const browser = await chromium.launch(process.env.CHROMIUM_PATH ? { executablePath: process.env.CHROMIUM_PATH, args: ['--no-sandbox'] } : { headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1100 }, colorScheme: 'dark' });
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  const ready = () => page.waitForFunction(() => !document.querySelector('[aria-busy="true"]') && /resultado/.test(document.querySelector('.catalog-result-meta')?.textContent ?? ''));
  await page.goto(`${base}/c/gpu`, { waitUntil: 'networkidle' }); await ready();
  assert.equal(await page.locator('html').getAttribute('data-theme'), 'light', 'light is the default even if the OS is dark');
  assert.equal(await page.locator('.product-row').count(), 24);
  await page.screenshot({ path: 'artifacts/stockfinder-preview.png' });
  await page.getByRole('button', { name: 'Ajustes de apariencia' }).click();
  await page.getByText('Obsidiana', { exact: true }).click();
  await page.getByRole('switch', { name: /Modo compacto/ }).check();
  assert.equal(await page.locator('html').getAttribute('data-theme'), 'dark');
  assert.equal(await page.locator('html').getAttribute('data-density'), 'compact');
  await page.getByRole('button', { name: 'Listo', exact: true }).click();
  await page.screenshot({ path: 'artifacts/stockfinder-dark-compact.png' });
  await page.reload({ waitUntil: 'networkidle' });
  assert.equal(await page.locator('html').getAttribute('data-theme'), 'dark');
  assert.equal(await page.locator('html').getAttribute('data-density'), 'compact');
  await page.getByRole('button', { name: 'Ajustes de apariencia' }).click();
  await page.getByText('Sistema', { exact: true }).click();
  assert.equal(await page.locator('html').getAttribute('data-theme'), 'dark', 'system follows prefers-color-scheme');
  await page.getByText('Medianoche', { exact: true }).click();
  await page.getByRole('switch', { name: /Reducir movimiento/ }).check();
  await page.getByRole('button', { name: 'Listo', exact: true }).click();
  await page.screenshot({ path: 'artifacts/stockfinder-blue-compact.png' });
  await page.getByRole('button', { name: 'Ajustes de apariencia' }).click();
  await page.getByRole('button', { name: 'Restablecer', exact: true }).click();
  assert.equal(await page.locator('html').getAttribute('data-theme'), 'light');
  await page.keyboard.press('Escape');
  await page.goto(`${base}/?q=9800X3D`, { waitUntil: 'networkidle' }); await ready();
  await page.locator('.product-name').first().click();
  await page.locator('.offers > div').first().waitFor();
  assert.ok(await page.locator('.offers > div').count() >= 1);
  assert.equal(await page.locator('.manufacturer-link').count(), 1);
  assert.ok((await page.locator('.offer-price').allTextContents()).every(price => price.includes('€')));
  await page.screenshot({ path: 'artifacts/stockfinder-verified-offers.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
  await page.getByRole('button', { name: 'Ajustes de apariencia' }).click();
  assert.ok(await page.getByRole('dialog', { name: 'Apariencia' }).isVisible());
  await page.keyboard.press('Escape');
  await page.screenshot({ path: 'artifacts/stockfinder-mobile-current.png', fullPage: true });
  assert.equal(errors.length, 0, errors.join('\n'));
  await browser.close();
  console.log('Current UI QA passed: light default, theme/density persistence, system theme, offers and mobile.');
})().catch(error => { console.error(error); process.exit(1); });
