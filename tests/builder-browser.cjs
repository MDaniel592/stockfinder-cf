const {chromium}=require('@playwright/test');
const assert=require('node:assert/strict');
(async()=>{
  const browser=await chromium.launch(process.env.CHROMIUM_PATH?{executablePath:process.env.CHROMIUM_PATH,args:['--no-sandbox']}:{});
  const page=await browser.newPage({viewport:{width:1440,height:1100},acceptDownloads:true});
  page.setDefaultTimeout(15000);
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  const base=process.env.TEST_BASE_URL||'http://127.0.0.1:8787';
  await page.goto(base,{waitUntil:'networkidle'});
  await page.getByRole('link',{name:'Configurador de PC',exact:true}).first().click();
  const choose=async(slot,id)=>{const trigger=page.locator(`#builder-slot-${slot}`);await page.waitForFunction(s=>!document.querySelector(s)?.disabled,`#builder-slot-${slot}`);await trigger.click();const detail=await (await page.request.get(`${base}/api/v1/builder/products/${id}`)).json();const query=detail.data.mpn||detail.data.name.split(/\s+/).slice(0,4).join(' ');await page.getByRole('combobox',{name:'Buscar por nombre, marca o referencia'}).fill(query);await page.locator(`.part-picker.is-open [data-product-id="${id}"]`).click();};
  await choose('cpu','amd-ryzen-7-9800x3d');
  const boardFilter=page.locator('.builder-part:has(#builder-slot-motherboard) .builder-filter-note');
  assert.ok((await boardFilter.innerText()).includes('socket AM5'));
  // The LGA1851 board is filtered out: show every board to provoke the socket conflict on purpose.
  await boardFilter.getByRole('button',{name:'Ver todos'}).click();
  await choose('motherboard','msi-mag-z890-tomahawk-wifi');
  assert.ok((await page.locator('.builder-check.error').innerText()).includes('Socket incompatible'));
  await choose('motherboard','asus-tuf-gaming-b850-plus-wifi');
  await choose('ram','corsair-vengeance-32gb-ddr5-6000-cl30');
  await choose('gpu','nvidia-geforce-rtx-5070');
  await choose('storage','samsung-990-pro-2tb');
  await choose('psu','corsair-rm850e-2025');
  await choose('case','fractal-north-charcoal-black-tg-dark');
  await choose('cooler','noctua-nh-d15-g2');
  assert.equal(await page.locator('.builder-check.error').count(),0);
  assert.ok((await page.locator('.builder-check-list').innerText()).includes('BIOS'));
  await page.getByLabel('Nombre de la lista').fill('Mi PC de prueba');
  await page.getByRole('button',{name:'Guardar lista',exact:true}).click();
  const key='stockfinder.pc-builds.v1';
  const stored=()=>page.evaluate(key=>JSON.parse(localStorage.getItem(key)),key);
  let initial=await stored();
  assert.equal(initial.builds.length,1);assert.equal(initial.builds[0].snapshots.length,1);
  const first=initial.builds[0].snapshots[0];
  assert.equal(first.total_items,8);assert.ok(first.priced_items>=1);
  const baselinePrice=first.items.find(p=>p.slot==='cpu').price_cents;
  assert.ok(Number.isSafeInteger(baselinePrice)&&baselinePrice>1000);
  await page.screenshot({path:'artifacts/stockfinder-builder.png',fullPage:true});
  // Simulated future price is confined to this isolated browser; no catalogue writes.
  await page.route('**/api/v1/builder/products/amd-ryzen-7-9800x3d',async route=>{
    const response=await route.fetch();const body=await response.json();
    body.data.min_price_cents=baselinePrice-1000;body.data.last_checked_at=new Date().toISOString();
    await route.fulfill({response,json:body});
  });
  await page.getByRole('button',{name:'Consultar precios actuales',exact:true}).click();
  await page.getByText(/Precios consultados en el catálogo/).waitFor();
  await page.getByRole('button',{name:'Guardar captura',exact:true}).click();
  let updated=await stored();
  assert.equal(updated.builds[0].snapshots.length,2);
  assert.deepEqual(updated.builds[0].snapshots[0],first);
  assert.equal(updated.builds[0].snapshots[1].items.find(p=>p.slot==='cpu').price_cents,baselinePrice-1000);
  assert.ok((await page.locator('.builder-delta').innerText()).includes('-10,00'));
  assert.ok((await page.locator('.builder-delta').innerText()).includes('Comparación parcial'));
  await page.screenshot({path:'artifacts/stockfinder-price-history.png',fullPage:true});
  const downloadPromise=page.waitForEvent('download');
  await page.getByRole('button',{name:'Exportar listas',exact:true}).click();
  await (await downloadPromise).saveAs(require('node:path').join(require('node:os').tmpdir(),'builder-export.json'));
  await page.reload({waitUntil:'networkidle'});
  await page.getByRole('button',{name:'Cargar lista',exact:true}).click();
  assert.deepEqual((await stored()).builds[0].snapshots[0],first);
  assert.equal((await stored()).builds[0].snapshots.length,2);
  await page.locator('.builder-file-actions input[type=file]').setInputFiles(require('node:path').join(require('node:os').tmpdir(),'builder-export.json'));
  await page.getByText(/listas importadas como copias nuevas/).waitFor();
  const imported=await stored();assert.equal(imported.builds.length,2);
  assert.notEqual(imported.builds[0].id,imported.builds[1].id);
  assert.equal(imported.builds[1].snapshots.length,2);
  await page.locator('.builder-file-actions input[type=file]').setInputFiles({name:'bad.json',mimeType:'application/json',buffer:Buffer.from('{"schema_version":1,"builds":[{}]}')});
  await page.getByRole('alert').waitFor();assert.equal((await stored()).builds.length,2);
  await page.setViewportSize({width:390,height:844});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.screenshot({path:'artifacts/stockfinder-builder-mobile.png',fullPage:true});
  assert.equal(errors.length,0,errors.join('\n'));
  await browser.close();console.log('Builder QA passed: compatibility, 8 slots, immutable snapshots, simulated price change, reload, export/import, invalid import, mobile.');
})().catch(error=>{console.error(error);process.exit(1)});
