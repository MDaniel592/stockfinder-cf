const {chromium}=require('@playwright/test');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
 const page=await browser.newPage({viewport:{width:1440,height:1000}}); page.setDefaultTimeout(15000);
 const errors=[]; page.on('pageerror',e=>errors.push(e.message));
 const base=process.env.TEST_BASE_URL||'http://127.0.0.1:8800';
 const response=await page.request.get(`${base}/api/v1/products?category=gpu&limit=1&stock=1`);
 const product=(await response.json()).data[0]; assert(product);
 await page.goto(`${base}/p/${product.slug}`,{waitUntil:'networkidle'});
 await page.getByLabel('Precio objetivo (€), opcional').fill('999999');
 await page.getByRole('button',{name:'Guardar favorito y aviso',exact:true}).click();
 await page.locator('.watchlist-header.has-updates').waitFor();
 await page.reload({waitUntil:'networkidle'});
 await page.getByRole('button',{name:/Favoritos y avisos/}).click();
 assert.match(await page.locator('.watchlist').innerText(),/Precio objetivo alcanzado/);
 await page.getByRole('button',{name:'Comparar compra por tiendas',exact:true}).click();
 await page.locator('.purchase-plans article').first().waitFor();
 assert.match(await page.locator('.purchase-plans').innerText(),/Pendiente/);
 await page.locator('details.purchase-costs > summary').click();
 await page.getByLabel('Destino',{exact:true}).selectOption('canarias');
 const costFields=page.locator('.purchase-planner fieldset input');
 for(let i=0;i<await costFields.count();i++) await costFields.nth(i).fill('0');
 assert(!/Pendiente/.test(await page.locator('.purchase-plans').innerText()));
 await page.getByLabel('Destino',{exact:true}).selectOption('peninsula');
 assert.match(await page.locator('.purchase-plans').innerText(),/Pendiente/);
 await page.setViewportSize({width:390,height:844});
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.screenshot({path:'artifacts/stockfinder-purchase-mobile.png',fullPage:true});
 await page.setViewportSize({width:1440,height:1000});
 await page.goto(`${base}/configurador`,{waitUntil:'networkidle'});
 const calls=[]; page.on('request',req=>{if(req.url().includes('/api/v1/builder/options?')) calls.push(new URL(req.url()));});
 await page.locator('#builder-slot-cpu').click();
 await page.locator('.part-picker.is-open [role=option]').first().waitFor();
 assert.equal(calls.length,1,'opening a picker must fetch one page');
 assert((await page.locator('.part-picker.is-open [role=option]').count())<=48);
 const search=page.getByRole('combobox',{name:'Buscar por nombre, marca o referencia'});
 await search.fill('9800'); await page.waitForResponse(res=>res.url().includes('q=9800'));
 await page.locator('.part-picker.is-open [role=option]').first().click();
 await page.locator('#builder-slot-motherboard').click();
 await page.locator('.part-picker.is-open [role=option]').first().waitFor();
 const board=calls.find(url=>url.searchParams.get('category')==='motherboard');
 assert(board?.searchParams.has('specs'),'compatibility is filtered before server pagination');
 assert.deepEqual(JSON.parse(board.searchParams.get('specs')), {Socket:['AM5']});
 await page.screenshot({path:'artifacts/stockfinder-progressive-picker.png'});
 await page.setViewportSize({width:390,height:844});
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.getByRole('combobox',{name:'Buscar por nombre, marca o referencia'}).fill('qz-no-such-product');
 await page.getByText(/Ningún componente(?: compatible)? coincide/).waitFor();
 assert.deepEqual(errors,[]); await browser.close(); console.log('Optimization browser QA passed: one-page picker, server compatibility, search, favorites/reload, target alert, destination costs and mobile.');
})().catch(e=>{console.error(e);process.exit(1)});
