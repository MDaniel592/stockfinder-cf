"""Generate D1 SQL that backfills offer_price_history from the PostgreSQL catalog_outbox (read-only).

Usage (SQL is written to stdout; redirect it on the host):
  docker compose --env-file .env -f infra/compose/compose.yaml run --rm -T \
    -v "$PWD/scripts:/app/scripts:ro" sync-agent python scripts/backfill_price_history.py \
    > artifacts/price-history-backfill.sql

One observation is emitted per offer for the first upsert and for every later upsert that changes price or
stock, replaying events in changed_at order. Statements are idempotent (NOT EXISTS on the exact row), so the
file can be applied more than once. Nothing is written to PostgreSQL or D1 by this script.
"""
import os
import sys
from datetime import datetime, timezone

import psycopg

QUERY = """SELECT entity_id, changed_at, data FROM catalog_outbox
           WHERE entity = 'offer' AND operation = 'upsert' ORDER BY entity_id, changed_at, version, event_id"""


def iso(value) -> str:
    """Same format as JavaScript's Date.toISOString() (UTC, milliseconds, Z)."""
    if isinstance(value, str):
        value = datetime.fromisoformat(value.replace('Z', '+00:00'))
    if value.tzinfo is None:
        value = value.replace(tzinfo=timezone.utc)
    value = value.astimezone(timezone.utc)
    return value.strftime('%Y-%m-%dT%H:%M:%S.') + f'{value.microsecond // 1000:03d}Z'


def quote(value: str) -> str:
    return "'" + str(value).replace("'", "''") + "'"


def observations(rows):
    """Yield (offer_id, product_id, shop_id, price_cents, in_stock, observed_at) for each change."""
    last = {}
    for offer_id, changed_at, data in rows:
        if not data:
            continue
        state = (int(data['price_cents']), int(bool(data['in_stock'])))
        if last.get(offer_id) == state:
            continue
        last[offer_id] = state
        observed = iso(data.get('last_checked_at') or changed_at)
        yield offer_id, data['product_id'], data['shop_id'], state[0], state[1], observed


def statement(row) -> str:
    offer_id, product_id, shop_id, price, stock, observed = row
    values = f"{quote(offer_id)},{quote(product_id)},{quote(shop_id)},{price},{stock},{quote(observed)}"
    return ("INSERT INTO offer_price_history(offer_id,product_id,shop_id,price_cents,in_stock,observed_at) "
            f"SELECT {values} WHERE NOT EXISTS(SELECT 1 FROM offer_price_history WHERE offer_id={quote(offer_id)} "
            f"AND observed_at={quote(observed)} AND price_cents={price} AND in_stock={stock});")


def main() -> int:
    with psycopg.connect(os.environ['DATABASE_URL'], options='-c default_transaction_read_only=on') as conn:
        rows = conn.execute(QUERY).fetchall()
    out = ['-- Generated by scripts/backfill_price_history.py from catalog_outbox (idempotent).']
    count = 0
    for row in observations(rows):
        out.append(statement(row))
        count += 1
    sys.stdout.write('\n'.join(out) + '\n')
    print(f'{count} observations from {len(rows)} offer events', file=sys.stderr)
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
